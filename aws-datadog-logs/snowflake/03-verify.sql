-- Verify all objects were created
SELECT 'Database' as OBJECT_TYPE, DATABASE_NAME as NAME, COMMENT
FROM INFORMATION_SCHEMA.DATABASES 
WHERE DATABASE_NAME = 'DEV_ENTECHLOG_RAW_DB';

SELECT 'Schema' as OBJECT_TYPE, SCHEMA_NAME as NAME, COMMENT
FROM INFORMATION_SCHEMA.SCHEMATA 
WHERE CATALOG_NAME = 'DEV_ENTECHLOG_RAW_DB' AND SCHEMA_NAME = 'DATADOG';

SELECT 'Table' as OBJECT_TYPE, TABLE_NAME as NAME, COMMENT
FROM INFORMATION_SCHEMA.TABLES 
WHERE TABLE_CATALOG = 'DEV_ENTECHLOG_RAW_DB' 
  AND TABLE_SCHEMA = 'DATADOG';

-- Check warehouse
SHOW WAREHOUSES LIKE 'DEV_ENTECHLOG_DATADOG_WH_XS';

-- Check role and user
SHOW ROLES LIKE 'DEV_SVC_ENTECHLOG_SNOW_DATADOG_ROLE';
SHOW USERS LIKE 'dev_svc_entechlog_snow_datadog_user';

-- Check grants
SHOW GRANTS TO ROLE DEV_SVC_ENTECHLOG_SNOW_DATADOG_ROLE;
